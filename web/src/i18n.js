const currentLocale = ref(localStorage.getItem('locale') || 'zh')

export function t(key, params) {
  const keys = key.split('.')
  let value = messages[currentLocale.value]
  for (const k of keys) {
    if (value && typeof value === 'object') {
      value = value[k]
    } else {
      return key
    }
  }
  if (typeof value !== 'string') return key
  if (params) {
    return value.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? `{${k}}`)
  }
  return value
}

export function setLocale(locale) {
  currentLocale.value = locale
  localStorage.setItem('locale', locale)
}

export function getLocale() {
  return currentLocale.value
}

export function formatDate(timestamp) {
  if (!timestamp) return '-'
  const ts = timestamp > 1e12 ? timestamp : timestamp * 1000
  const localeMap = { zh: 'zh-CN', en: 'en-US' }
  return new Date(ts).toLocaleString(localeMap[currentLocale.value] || 'en-US')
}

const locale = computed(() => currentLocale.value)

export function useI18n() {
  return { t, setLocale, getLocale, locale, formatDate }
}
